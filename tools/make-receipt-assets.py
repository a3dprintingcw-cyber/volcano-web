"""Builds src/receipt-assets.js: 1-bit glyph bitmaps and the logo for printed tickets.

Run from the repo root:  python3 tools/make-receipt-assets.py
Needs Pillow and fontTools (to read the woff2 fonts in public/fonts).
"""
import base64, io, json, os, tempfile
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

FONTS = {
    # name: (woff2 file, pixel size)
    'body': ('barlow-latin-500-normal', 27),
    'bold': ('barlow-latin-700-normal', 29),
    'big': ('barlow-latin-700-normal', 42),
    'number': ('bowlby-one-latin-400-normal', 56),
}
CHARS = [chr(c) for c in list(range(32, 127)) + list(range(160, 256))]

def ttf(name):
    f = TTFont(f'public/fonts/{name}.woff2'); f.flavor = None
    path = os.path.join(tempfile.gettempdir(), name + '.ttf'); f.save(path); return path

def pack(img):
    w, h = img.size; px = img.load(); out = bytearray()
    for y in range(h):
        byte = 0; n = 0
        for x in range(w):
            byte = (byte << 1) | (1 if px[x, y] < 128 else 0); n += 1
            if n == 8: out.append(byte); byte = 0; n = 0
        if n: out.append(byte << (8 - n))
    return base64.b64encode(bytes(out)).decode()

fonts = {}
for key, (file, size) in FONTS.items():
    font = ImageFont.truetype(ttf(file), size)
    ascent, descent = font.getmetrics(); h = ascent + descent
    glyphs = {}
    for ch in CHARS:
        w = max(1, round(font.getlength(ch)))
        img = Image.new('L', (w, h), 255)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=0)
        glyphs[ord(ch)] = [w, pack(img)]
    fonts[key] = {'h': h, 'g': glyphs}

logo = Image.open('public/img/logo.png').convert('RGB')
lw = 440
logo = logo.resize((lw, round(lw * logo.height / logo.width)), Image.LANCZOS)
# Everything brighter than the dark background (the yellow and the red) prints black.
gray = Image.new('L', logo.size, 255); lp = logo.load(); gp = gray.load()
for y in range(logo.height):
    for x in range(logo.width):
        r, g, b = lp[x, y]
        gp[x, y] = 0 if max(r, g, b) > 110 else 255
bbox = Image.eval(gray, lambda v: 255 - v).getbbox(); gray = gray.crop(bbox)

with open('src/receipt-assets.js', 'w') as f:
    f.write('// Generated by tools/make-receipt-assets.py. Do not edit by hand.\n')
    f.write('// 1-bit bitmaps (1 = black), rows packed MSB first, base64.\n')
    f.write('export const FONTS = ' + json.dumps(fonts, separators=(',', ':')) + ';\n')
    f.write('export const LOGO = ' + json.dumps({'w': gray.width, 'h': gray.height, 'd': pack(gray)}) + ';\n')
print('ok', os.path.getsize('src/receipt-assets.js') // 1024, 'KB', gray.size)
