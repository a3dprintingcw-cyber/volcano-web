// Turns menu/rooftop.mjs into db/rooftop-seed.sql (and prints the same inserts for a migration).
// Run with: npm run rooftop:build
// The seed replaces only the rooftop (Volcano Experience) menu. It never touches the
// street food menu or any orders.
import { writeFileSync } from 'node:fs';
import { rooftopMenu, rooftopSettings } from '../menu/rooftop.mjs';

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const cents = (guilders) => Math.round(guilders * 100);

// Own id ranges, far above the street food menu, so the two seeds never collide.
const CAT_BASE = 100;
const ITEM_BASE = 10000;
const GROUP_BASE = 10000;
const OPTION_BASE = 100000;

export function rooftopInserts() {
  const out = [];
  let itemId = ITEM_BASE;
  let groupId = GROUP_BASE;
  let optionId = OPTION_BASE;
  rooftopMenu.forEach((cat, ci) => {
    const catId = CAT_BASE + ci + 1;
    out.push(
      `INSERT INTO categories (id, slug, name, note, sort, venue) VALUES (${catId}, ${q(`rooftop-${cat.slug}`)}, ${q(cat.name)}, ${q(cat.note || '')}, ${CAT_BASE + ci}, 'rooftop');`
    );
    cat.items.forEach((item, ii) => {
      itemId += 1;
      out.push(
        `INSERT INTO items (id, category_id, name, description, price_cents, image, alcohol, available, sort) VALUES (${itemId}, ${catId}, ${q(item.name)}, ${q(item.desc || '')}, ${cents(item.price || 0)}, ${q(item.image || '')}, ${item.alcohol ? 1 : 0}, 1, ${ii});`
      );
      (item.groups || []).forEach((group, gi) => {
        groupId += 1;
        out.push(
          `INSERT INTO option_groups (id, item_id, name, min_choices, max_choices, sort) VALUES (${groupId}, ${itemId}, ${q(group.name)}, ${group.min}, ${group.max}, ${gi});`
        );
        group.choices.forEach((choice, oi) => {
          optionId += 1;
          out.push(
            `INSERT INTO options (id, group_id, name, price_cents, alcohol, available, sort) VALUES (${optionId}, ${groupId}, ${q(choice.name)}, ${cents(choice.price || 0)}, ${choice.alcohol ? 1 : 0}, 1, ${oi});`
          );
        });
      });
    });
  });
  // Inserted only when missing, so re-seeding keeps what the manager changed.
  out.push(`INSERT OR IGNORE INTO settings (key, value) VALUES ('rooftop', ${q(JSON.stringify(rooftopSettings))});`);
  return out;
}

const ROOFTOP_ITEMS = "SELECT i.id FROM items i JOIN categories c ON c.id = i.category_id WHERE c.venue = 'rooftop'";
export const rooftopDeletes = [
  `DELETE FROM options WHERE group_id IN (SELECT id FROM option_groups WHERE item_id IN (${ROOFTOP_ITEMS}));`,
  `DELETE FROM option_groups WHERE item_id IN (${ROOFTOP_ITEMS});`,
  `DELETE FROM items WHERE id IN (${ROOFTOP_ITEMS});`,
  "DELETE FROM categories WHERE venue = 'rooftop';",
];

if (import.meta.url === `file://${process.argv[1]}`) {
  const lines = ['-- Generated by scripts/build-rooftop.mjs. Do not edit by hand.', ...rooftopDeletes, ...rooftopInserts()];
  writeFileSync(new URL('../db/rooftop-seed.sql', import.meta.url), lines.join('\n') + '\n');
  console.log(`rooftop-seed.sql written: ${rooftopMenu.length} categories, ${rooftopMenu.reduce((n, c) => n + c.items.length, 0)} items`);
}
